.section .text
    .globl _start

_start:
    # 初始化錯誤計數器 x8 為 0
    li  x8, 0

    # ---------------------------------------------------------
    # Test 1: 測試 JAL
    # ---------------------------------------------------------
    # 下一行是 JAL，它應該跳到 target_1
    jal x0, target_1

    # [VICTIM 1]
    # 如果你的 CPU 有 Bug (JAL 沒 flush ID)，這行會被執行
    # x8 將會變成 1
    addi x8, x8, 1

target_1:
    nop
    nop

    # ---------------------------------------------------------
    # Test 2: 測試 JALR
    # ---------------------------------------------------------
    # 準備跳轉地址
    la  x1, target_2

    # 下一行是 JALR，它應該跳到 target_2
    jalr x0, 0(x1)

    # [VICTIM 2]
    # 如果你的 CPU 有 Bug (JALR 沒 flush ID)，這行會被執行
    # x8 將會增加 2 (變成 1+2=3 或 0+2=2)
    addi x8, x8, 2

target_2:
    nop
    nop

    # ---------------------------------------------------------
    # 結束檢查
    # ---------------------------------------------------------
    # 如果 x8 == 0，代表 PASS (兩次跳轉後面的指令都被成功 Flush)
    # 如果 x8 != 0，代表 FAIL

finish:
    j finish